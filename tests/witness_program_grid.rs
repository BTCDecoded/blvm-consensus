//! Witness-program classification for every version byte and program length.
//!
//! A witness program is `OP_0` or `OP_1` through `OP_16`, then a direct push of
//! 2 to 40 bytes, and nothing after that push. `OP_1NEGATE` and `OP_RESERVED`
//! sit in the numeric-opcode range and are not versions. A trailing byte or a
//! short body is not a witness program.
//!
//! Standard programs are version 0 with 20 or 32 bytes, and version 1 with 32
//! bytes. Any other version-0 length is invalid. A later version, and version 1
//! at any other length, is upgradable. Version extraction only names version 0
//! and version 1. The program-byte extractor does not look at the version byte.

use blvm_consensus::opcodes::{OP_0, OP_1, OP_1NEGATE, OP_16, OP_RESERVED};
use blvm_consensus::witness::{
    WitnessVersion, calculate_transaction_weight_segwit, extract_witness_program,
    extract_witness_version, is_any_witness_program, is_invalid_v0_witness_program,
    is_pay_to_anchor, is_standard_witness_program, is_upgradable_witness_program,
    validate_witness_program_length, weight_to_vsize,
};

fn script(opcode: u8, length: u8, shape: u8) -> Vec<u8> {
    let payload = match shape {
        0 => length as usize,
        1 => length as usize + 1,
        2 => length as usize - 1,
        _ => unreachable!("shape is exact, trailing, or truncated"),
    };
    let mut out = Vec::with_capacity(2 + payload);
    out.push(opcode);
    out.push(length);
    out.extend(std::iter::repeat(0x11).take(payload));
    out
}

#[test]
fn witness_program_class_matches_the_version_and_length_rule() {
    assert_eq!(OP_0, 0x00);
    assert_eq!(OP_1NEGATE, 0x4f);
    assert_eq!(OP_RESERVED, 0x50);
    assert_eq!(OP_1, 0x51);
    assert_eq!(OP_16, 0x60);
    for (i, &(opcode, length, shape, any, standard, invalid_v0, upgradable, version)) in
        ROWS.iter().enumerate()
    {
        let script = script(opcode, length, shape);
        assert_eq!(is_any_witness_program(&script), any, "row {i} any");
        assert_eq!(
            is_standard_witness_program(&script),
            standard,
            "row {i} standard"
        );
        assert_eq!(
            is_invalid_v0_witness_program(&script),
            invalid_v0,
            "row {i} v0"
        );
        assert_eq!(
            is_upgradable_witness_program(&script),
            upgradable,
            "row {i} upgradable"
        );
        assert!(!is_pay_to_anchor(&script), "row {i} is not the anchor");
        let extracted = extract_witness_version(&script);
        match version {
            0 => assert!(extracted.is_none(), "row {i} version"),
            1 => assert_eq!(extracted, Some(WitnessVersion::SegWitV0), "row {i} version"),
            2 => assert_eq!(
                extracted,
                Some(WitnessVersion::TaprootV1),
                "row {i} version"
            ),
            _ => unreachable!("version column is 0, 1, or 2"),
        }
        let program = extract_witness_program(&script, WitnessVersion::SegWitV0);
        if shape == 0 && (2..=40).contains(&length) {
            assert_eq!(program.as_deref(), Some(&script[2..]), "row {i} program");
        } else {
            assert!(program.is_none(), "row {i} program");
        }
        if let Some(version) = extracted {
            let bytes = program.expect("a named version has a program");
            let length_ok = match version {
                WitnessVersion::SegWitV0 => length == 20 || length == 32,
                WitnessVersion::TaprootV1 => length == 32,
            };
            assert_eq!(
                validate_witness_program_length(&bytes, version),
                length_ok,
                "row {i} length"
            );
            assert_eq!(length_ok, standard, "row {i} standard length");
        }
    }
}

#[test]
fn pay_to_anchor_is_only_the_four_byte_pattern() {
    let anchor = [OP_1, 0x02, 0x4e, 0x73];
    assert!(is_pay_to_anchor(&anchor));
    assert!(is_any_witness_program(&anchor));
    assert!(is_upgradable_witness_program(&anchor));
    assert!(!is_standard_witness_program(&anchor));
    for index in 0..anchor.len() {
        let mut changed = anchor;
        changed[index] ^= 0x01;
        assert!(!is_pay_to_anchor(&changed), "byte {index}");
    }
}

#[test]
fn a_non_witness_transaction_weighs_four_times_its_size() {
    for size in 0u64..=4_096 {
        let bare = calculate_transaction_weight_segwit(size, size);
        assert_eq!(bare, size.saturating_mul(4), "bare {size}");
        assert_eq!(weight_to_vsize(bare), size, "bare vsize {size}");
        for extra in 1..=3 {
            let total = size + extra;
            let weight = calculate_transaction_weight_segwit(size, total);
            assert_eq!(weight, size * 3 + total, "extra {extra} at {size}");
            assert_eq!(weight_to_vsize(weight), size + 1, "ceil {extra} at {size}");
        }
    }
    assert_eq!(
        calculate_transaction_weight_segwit(1_000_000, 1_000_000),
        4_000_000
    );
    assert_eq!(weight_to_vsize(4_000_000), 1_000_000);
    assert_eq!(weight_to_vsize(4_000_001), 1_000_001);
}

