//! Signature-operation counts, including opcodes hidden inside a push.
//!
//! `OP_CHECKSIG` and `OP_CHECKSIGVERIFY` count as one. `OP_CHECKMULTISIG` and
//! `OP_CHECKMULTISIGVERIFY` count as 20, or as N when accurate counting is on
//! and the opcode immediately before them is `OP_1` through `OP_16`. A push
//! consumes the bytes that follow it, so a checksig byte inside the push is
//! not an opcode. `OP_CHECKSIGADD` counts only in a tapscript.

use blvm_consensus::opcodes::{
    OP_CHECKMULTISIG, OP_CHECKSIG, OP_CHECKSIGADD, OP_PUSHDATA1, OP_PUSHDATA2, OP_PUSHDATA4,
};
use blvm_consensus::sigop::{count_sigops_in_script, count_tapscript_sigops};

fn preceded(prev: u8, multisig: u8, leading: u8) -> Vec<u8> {
    let mut script = Vec::with_capacity(3);
    if leading == 1 {
        script.push(OP_CHECKSIG);
    }
    script.push(prev);
    script.push(multisig);
    script
}

fn pushed(kind: u8, length: u16, trailing: u8) -> Vec<u8> {
    let mut script = Vec::new();
    let payload = std::iter::repeat(OP_CHECKSIG).take(length as usize);
    match kind {
        1 => {
            script.push(length as u8);
            script.extend(payload);
        }
        2 => {
            script.push(OP_PUSHDATA1);
            script.push(length as u8);
            script.extend(payload);
        }
        3 => {
            script.push(OP_PUSHDATA2);
            script.extend(length.to_le_bytes());
            script.extend(payload);
        }
        _ => unreachable!("kind is a direct push, PUSHDATA1, or PUSHDATA2"),
    }
    if trailing == 1 {
        script.push(OP_CHECKSIG);
    }
    script
}

#[test]
fn the_opcode_before_a_multisig_sets_its_accurate_count() {
    assert_eq!(OP_CHECKSIG, 0xac);
    assert_eq!(OP_CHECKMULTISIG, 0xae);
    for (i, &(prev, multisig, accurate, leading, legacy, tapscript)) in PREV.iter().enumerate() {
        let script = preceded(prev, multisig, leading);
        assert_eq!(
            count_sigops_in_script(&script, accurate == 1),
            legacy,
            "prev row {i}"
        );
        assert_eq!(
            count_tapscript_sigops(&script),
            tapscript,
            "prev row {i} tapscript"
        );
    }
}

#[test]
fn checksig_bytes_inside_a_push_are_not_opcodes() {
    for (i, &(kind, length, trailing, legacy, tapscript)) in PUSH.iter().enumerate() {
        let script = pushed(kind, length, trailing);
        assert_eq!(
            count_sigops_in_script(&script, true),
            legacy,
            "push row {i}"
        );
        assert_eq!(
            count_sigops_in_script(&script, false),
            legacy,
            "push row {i} fast"
        );
        assert_eq!(
            count_tapscript_sigops(&script),
            tapscript,
            "push row {i} tapscript"
        );
    }
}

#[test]
fn a_single_opcode_counts_only_the_checksig_family() {
    for opcode in 0u16..=255 {
        let script = vec![opcode as u8];
        let legacy = match opcode as u8 {
            0xac | 0xad => 1,
            0xae | 0xaf => 20,
            _ => 0,
        };
        let tapscript = match opcode as u8 {
            0xac | 0xad | OP_CHECKSIGADD => 1,
            _ => 0,
        };
        assert_eq!(
            count_sigops_in_script(&script, true),
            legacy,
            "opcode {opcode:#x}"
        );
        assert_eq!(
            count_sigops_in_script(&script, false),
            legacy,
            "opcode {opcode:#x} fast"
        );
        assert_eq!(
            count_tapscript_sigops(&script),
            tapscript,
            "opcode {opcode:#x} tapscript"
        );
    }
    let empty = Vec::<u8>::new();
    assert_eq!(count_sigops_in_script(&empty, true), 0);
    assert_eq!(count_tapscript_sigops(&empty), 0);
}

#[test]
fn pushdata4_reads_its_length_as_little_endian() {
    let little = vec![
        OP_PUSHDATA4,
        0x01,
        0x00,
        0x00,
        0x00,
        OP_CHECKSIG,
        0x51,
        OP_CHECKMULTISIG,
    ];
    assert_eq!(count_sigops_in_script(&little, true), 1);
    assert_eq!(count_tapscript_sigops(&little), 0);
    let swapped = vec![
        OP_PUSHDATA4,
        0x00,
        0x01,
        0x00,
        0x00,
        OP_CHECKSIG,
        0x51,
        OP_CHECKMULTISIG,
    ];
    assert_eq!(count_sigops_in_script(&swapped, true), 0);
    assert_eq!(count_sigops_in_script(&vec![OP_PUSHDATA1], true), 0);
    assert_eq!(count_sigops_in_script(&vec![OP_PUSHDATA2, 0x01], true), 0);
    assert_eq!(
        count_sigops_in_script(&vec![OP_PUSHDATA4, 0x01, 0x00], true),
        0
    );
}

