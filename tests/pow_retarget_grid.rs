//! Mainnet difficulty retarget, and the testnet walk that stays inside one period.
//!
//! On a 2,016-block boundary the next compact target is the last block's target
//! times the measured span, divided by the 1,209,600-second target timespan.
//! The span is clamped to one quarter and four times that timespan, and the
//! result is capped at the proof-of-work limit `0x1d00ffff`.
//!
//! The grid is anchored to mainnet block 112,896: previous bits 453,062,093 and
//! a span of 882,515 seconds produce 453,041,201.
//!
//! Off a boundary, testnet and regtest may walk backward through minimum-difficulty
//! blocks. The walk stops on the first block of the period and does not read
//! the previous period. A block more than two target spacings after its parent
//! takes the proof-of-work limit directly.

use blvm_consensus::Network;
use blvm_consensus::pow::next_required_bits;

const TIMESPAN: u64 = 2_016 * 600;
const ORIGIN: u64 = 1_600_000_000;
const POW_LIMIT: u64 = 0x1d00_ffff;
const REAL_BITS: u64 = 0x1b01_2dcd;

fn mainnet_retarget(prev_bits: u64, span: u64) -> u64 {
    let last = ORIGIN + span;
    let ancestor = |height: u64| match height {
        0 => Some((prev_bits, ORIGIN)),
        2015 => Some((prev_bits, last)),
        _ => None,
    };
    next_required_bits(Network::Mainnet, 2016, last, &ancestor)
        .expect("retarget inputs are in range")
        .expect("height 2016 has a parent")
}

#[test]
fn mainnet_retarget_grid_matches_the_clamped_ratio() {
    for (i, &(prev, span, expected)) in ROWS.iter().enumerate() {
        let got = mainnet_retarget(prev, span);
        assert_eq!(
            got, expected,
            "row {i}: previous {prev:#x} span {span} produced {got:#x}"
        );
    }
}

#[test]
fn mainnet_height_112896_span_matches_the_chain() {
    let span = 1_299_683_275 - 1_298_800_760;
    assert_eq!(span, 882_515);
    assert_eq!(mainnet_retarget(453_062_093, span), 453_041_201);
}

#[test]
fn zero_mantissa_retargets_to_zero() {
    assert_eq!(mainnet_retarget(0x1b00_0000, TIMESPAN), 0);
}

#[test]
fn the_compact_sign_bit_is_not_part_of_the_target() {
    let span = 882_515u64;
    assert_eq!(
        mainnet_retarget(REAL_BITS | 0x0080_0000, span),
        mainnet_retarget(REAL_BITS, span)
    );
}

fn on_time(network: Network, tip: u64, real_height: u64, limit: u64) -> u64 {
    let ancestor = |height: u64| {
        let bits = if height == real_height {
            REAL_BITS
        } else {
            limit
        };
        Some((bits, 1_000_000 + height * 600))
    };
    let parent_time = 1_000_000 + tip * 600;
    next_required_bits(network, tip + 1, parent_time + 600, &ancestor)
        .expect("ancestors exist")
        .expect("not genesis")
}

#[test]
fn testnet_walk_finds_real_bits_at_the_parent_the_middle_and_the_period_start() {
    for tip in 1..2015 {
        assert_eq!(
            on_time(Network::Testnet, tip, tip, POW_LIMIT),
            REAL_BITS,
            "parent {tip}"
        );
        assert_eq!(
            on_time(Network::Testnet, tip, tip / 2, POW_LIMIT),
            REAL_BITS,
            "middle {tip}"
        );
        assert_eq!(
            on_time(Network::Testnet, tip, 0, POW_LIMIT),
            REAL_BITS,
            "start {tip}"
        );
    }
}

#[test]
fn testnet_walk_stops_on_the_first_block_of_the_period() {
    for tip in 2016..4031 {
        assert_eq!(
            on_time(Network::Testnet, tip, 2016, POW_LIMIT),
            REAL_BITS,
            "boundary visible at {tip}"
        );
        assert_eq!(
            on_time(Network::Testnet, tip, 2015, POW_LIMIT),
            POW_LIMIT,
            "previous period hidden at {tip}"
        );
    }
}

#[test]
fn testnet_block_later_than_two_spacings_uses_the_limit_without_walking() {
    let ancestor = |height: u64| {
        if height == 100 {
            Some((REAL_BITS, 1_000_000))
        } else {
            None
        }
    };
    let bits = next_required_bits(Network::Testnet, 101, 1_000_000 + 1_201, &ancestor)
        .expect("parent exists")
        .expect("not genesis");
    assert_eq!(bits, POW_LIMIT);
}

#[test]
fn regtest_walk_stays_inside_its_144_block_period() {
    let limit = 0x207f_ffff;
    for tip in 1..143 {
        assert_eq!(
            on_time(Network::Regtest, tip, 0, limit),
            REAL_BITS,
            "tip {tip}"
        );
    }
    for tip in 144..287 {
        assert_eq!(
            on_time(Network::Regtest, tip, 144, limit),
            REAL_BITS,
            "boundary visible at {tip}"
        );
        assert_eq!(
            on_time(Network::Regtest, tip, 143, limit),
            limit,
            "previous period hidden at {tip}"
        );
    }
}

#[test]
fn regtest_boundary_does_not_retarget() {
    let ancestor = |height: u64| match height {
        143 => Some((REAL_BITS, 1_000)),
        0 => Some((POW_LIMIT, 1)),
        _ => None,
    };
    let bits = next_required_bits(Network::Regtest, 144, 2_000, &ancestor)
        .expect("parent exists")
        .expect("not genesis");
    assert_eq!(bits, REAL_BITS);
}

#[test]
fn testnet4_retargets_from_the_first_block_not_the_min_difficulty_tail() {
    let ancestor = |height: u64| match height {
        0 => Some((REAL_BITS, ORIGIN)),
        2015 => Some((POW_LIMIT, ORIGIN + TIMESPAN)),
        _ => None,
    };
    let from_tail = next_required_bits(Network::Testnet, 2016, ORIGIN + TIMESPAN, &ancestor)
        .expect("ancestors exist")
        .expect("not genesis");
    let from_head = next_required_bits(Network::Testnet4, 2016, ORIGIN + TIMESPAN, &ancestor)
        .expect("ancestors exist")
        .expect("not genesis");
    assert_eq!(from_tail, POW_LIMIT);
    assert_eq!(from_head, mainnet_retarget(REAL_BITS, TIMESPAN));
}

