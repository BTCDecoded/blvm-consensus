//! Absolute locktime comparison, and relative locktime over the whole 16-bit field.
//!
//! `OP_CHECKLOCKTIMEVERIFY` accepts a stack locktime only when it has the same
//! kind as the transaction locktime and is less than or equal to it. A value
//! below 500,000,000 is a block height. A value at or above that cut is a Unix
//! time. A larger number on the other side of the cut does not satisfy the check.
//!
//! BIP68 stores the relative lock in the low 16 bits. A block lock of `n` is
//! satisfied strictly after `coin_height + n - 1`. A time lock is the same
//! shape in units of 512 seconds, measured from the prior block's median time.
//! Bit 22 selects time. Bit 31 disables the lock. The other bits above the low
//! 16 do not change the value.

use blvm_consensus::locktime::{
    LocktimeType, check_bip65, check_bip112, decode_locktime_value, encode_locktime_value,
    get_locktime_type,
};
use blvm_consensus::sequence_locks::calculate_sequence_locks;
use blvm_consensus::{OutPoint, Transaction, TransactionInput, TransactionOutput};

const THRESHOLD: u32 = 500_000_000;
const COIN_HEIGHT: u64 = 1_000_000;
const COIN_TIME: i64 = 1_600_000_000;
const TYPE_FLAG: u32 = 0x0040_0000;
const DISABLE_FLAG: u32 = 0x8000_0000;
const NOISE_BITS: u32 = 0x003f_0000;

fn sample_tx(version: u64, sequence: u64) -> Transaction {
    Transaction {
        version,
        inputs: vec![TransactionInput {
            prevout: OutPoint {
                hash: [0x11; 32],
                index: 0,
            },
            script_sig: vec![],
            sequence,
        }]
        .into(),
        outputs: vec![TransactionOutput {
            value: 1_000,
            script_pubkey: vec![],
        }]
        .into(),
        lock_time: 0,
    }
}

#[test]
fn cltv_accepts_only_the_same_kind_at_or_below_the_transaction_locktime() {
    assert_eq!(get_locktime_type(THRESHOLD - 1), LocktimeType::BlockHeight);
    assert_eq!(get_locktime_type(THRESHOLD), LocktimeType::Timestamp);
    for (i, &(tx, stack, accept)) in ROWS.iter().enumerate() {
        assert_eq!(
            check_bip65(tx, stack),
            accept,
            "row {i}: tx {tx} stack {stack}"
        );
    }
}

#[test]
fn every_relative_lock_value_is_coin_plus_value_minus_one() {
    for value in 0u32..=0xffff {
        let height =
            calculate_sequence_locks(&sample_tx(2, value as u64), 1, &[COIN_HEIGHT], None).unwrap();
        let expected_height = COIN_HEIGHT as i64 + value as i64 - 1;
        assert_eq!(height, (expected_height, -1), "height value {value}");

        let noisy = calculate_sequence_locks(
            &sample_tx(2, (value | NOISE_BITS) as u64),
            1,
            &[COIN_HEIGHT],
            None,
        )
        .unwrap();
        assert_eq!(noisy, height, "noise bits value {value}");

        let time = calculate_sequence_locks(
            &sample_tx(2, (value | TYPE_FLAG) as u64),
            1,
            &[COIN_HEIGHT],
            Some(&[COIN_TIME]),
        )
        .unwrap();
        let expected_time = COIN_TIME + ((value as i64) << 9) - 1;
        assert_eq!(time, (-1, expected_time), "time value {value}");

        let disabled = calculate_sequence_locks(
            &sample_tx(2, (value | DISABLE_FLAG) as u64),
            1,
            &[COIN_HEIGHT],
            None,
        )
        .unwrap();
        assert_eq!(disabled, (-1, -1), "disabled value {value}");
    }
}

#[test]
fn a_relative_lock_fails_on_its_threshold_and_passes_on_the_next_unit() {
    let (min_height, _) =
        calculate_sequence_locks(&sample_tx(2, 1), 1, &[COIN_HEIGHT], None).unwrap();
    assert!(!blvm_consensus::sequence_locks::evaluate_sequence_locks(
        min_height as u64,
        0,
        (min_height, -1)
    ));
    assert!(blvm_consensus::sequence_locks::evaluate_sequence_locks(
        min_height as u64 + 1,
        0,
        (min_height, -1)
    ));
    let (_, min_time) = calculate_sequence_locks(
        &sample_tx(2, TYPE_FLAG as u64 | 1),
        1,
        &[COIN_HEIGHT],
        Some(&[COIN_TIME]),
    )
    .unwrap();
    assert!(!blvm_consensus::sequence_locks::evaluate_sequence_locks(
        1,
        min_time as u64,
        (-1, min_time)
    ));
    assert!(blvm_consensus::sequence_locks::evaluate_sequence_locks(
        1,
        min_time as u64 + 1,
        (-1, min_time)
    ));
}

#[test]
fn versions_below_two_do_not_enforce_a_relative_lock() {
    for version in [0u64, 1, 2, 0x8000_0000, 0xffff_ffff, (1 << 32) + 2] {
        let (height, time) =
            calculate_sequence_locks(&sample_tx(version, 10), 1, &[COIN_HEIGHT], None).unwrap();
        if (version as u32) >= 2 {
            assert_eq!(height, COIN_HEIGHT as i64 + 9, "version {version}");
            assert_eq!(time, -1);
        } else {
            assert_eq!((height, time), (-1, -1), "version {version}");
        }
    }
    let (height, time) =
        calculate_sequence_locks(&sample_tx(2, 10), 0, &[COIN_HEIGHT], None).unwrap();
    assert_eq!((height, time), (-1, -1));
}

#[test]
fn csv_compares_the_low_16_bits_only_when_the_type_bit_matches() {
    for value in 0u32..=0xffff {
        assert!(check_bip112(value, value), "equal {value}");
        assert!(
            check_bip112(value, value | NOISE_BITS),
            "input noise {value}"
        );
        assert!(
            check_bip112(value | NOISE_BITS, value),
            "stack noise {value}"
        );
        if value > 0 {
            assert!(!check_bip112(value, value - 1), "shorter {value}");
        }
        assert!(
            !check_bip112(value | TYPE_FLAG, value),
            "type mismatch {value}"
        );
        assert!(
            !check_bip112(value, value | TYPE_FLAG),
            "type mismatch {value}"
        );
        assert!(
            check_bip112(value | TYPE_FLAG, value | TYPE_FLAG),
            "time equal {value}"
        );
        assert!(
            check_bip112(value | DISABLE_FLAG, value | DISABLE_FLAG),
            "disable bit is not the comparison {value}"
        );
    }
}

#[test]
fn script_number_roundtrip_covers_every_relative_lock_value() {
    for byte in 0u16..=255 {
        let raw = byte as u8;
        let decoded = decode_locktime_value(&[raw]).unwrap();
        let expect = if raw & 0x80 == 0 {
            raw as i64
        } else {
            -((raw & 0x7f) as i64)
        };
        assert_eq!(decoded, expect, "byte {raw:#x}");
    }
    assert_eq!(decode_locktime_value(&[]), Some(0));
    assert_eq!(decode_locktime_value(&[0x80]), Some(0));
    assert_eq!(decode_locktime_value(&[0; 6]), None);
    for value in 0u32..=0xffff {
        let encoded = encode_locktime_value(value);
        assert_eq!(decode_locktime_value(&encoded), Some(value as i64));
        if value >= 0x80 && value <= 0xff {
            assert_eq!(encoded, vec![value as u8, 0]);
        }
        if value >= 0x8000 {
            assert_eq!(encoded, vec![(value & 0xff) as u8, (value >> 8) as u8, 0]);
        }
    }
}

